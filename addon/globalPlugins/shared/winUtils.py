def findWindowByProcessName(pName="thunderbird.exe"):
	"""
	Iterates through visible top-level windows and returns the HWND of the first one
	belonging to the specified process name. Returns 0 if not found.
	"""
	foundHwnd = 0
	targetProcessName = pName.lower()

	def enumWindowsCallback(hwnd, lparam):
		nonlocal foundHwnd

		# Check if the window is visible
		if IsWindowVisible(hwnd):
			pid = wintypes.DWORD()
			GetWindowThreadProcessId(hwnd, ctypes.byref(pid))

			if pid.value != 0:
				# Open process to query its executable path
				hProcess = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid.value)
				if hProcess:
					try:
						bufferSize = wintypes.DWORD(1024)
						buffer = ctypes.create_unicode_buffer(bufferSize.value)
						
						if QueryFullProcessImageNameW(hProcess, 0, buffer, ctypes.byref(bufferSize)):
							# Extract executable name from full path
							exePath = buffer.value
							exeName = exePath.rsplit('\\', 1)[-1].lower()

							if exeName == targetProcessName:
								foundHwnd = hwnd
								return False  # Stop enumeration immediately
					finally:
						CloseHandle(hProcess)

		return True  # Continue enumeration

	# Execute window enumeration
	EnumWindows(EnumWindowsProc(enumWindowsCallback), 0)

	return foundHwnd


def findWindowByTitleEnding(titleEnd):
	"""
	Iterates through visible windows and returns the HWND of the first one
	whose title ends with `titleEnd`. Returns 0 if not found.
	"""
	found_hwnd = 0

	def enum_windows_callback(hwnd, lparam):
		nonlocal found_hwnd

		# Check if the window is visible
		if IsWindowVisible(hwnd):
			# Retrieve the window title length
			length = GetWindowTextLengthW(hwnd)
			if length > 0:
				buffer = ctypes.create_unicode_buffer(length + 1)
				GetWindowTextW(hwnd, buffer, length + 1)
				title = buffer.value

				# Check if the title ends with the specified substring
				if title.endswith(titleEnd):
					found_hwnd = hwnd
					return False  # Stop enumeration immediately

		return True  # Continue enumeration

	# Execute window enumeration
	EnumWindows(EnumWindowsProc(enum_windows_callback), 0)

	return found_hwnd

