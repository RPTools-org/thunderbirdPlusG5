def restoreAndFocusWindow(hwnd):
	"""Restores the window specified by hwnd and brings it to the foreground."""
	if not hwnd or not user32.IsWindow(hwnd):
		return False

	# 1. Restore the window if minimized, otherwise ensure it is shown
	if user32.IsIconic(hwnd):
		user32.ShowWindow(hwnd, SW_RESTORE)
	else:
		user32.ShowWindow(hwnd, SW_SHOW)

	# 2. Bypass SetForegroundWindow restrictions using AttachThreadInput
	foreground_hwnd = user32.GetForegroundWindow()
	if foreground_hwnd != hwnd:
		current_thread_id = kernel32.GetCurrentThreadId()
		window_thread_id = user32.GetWindowThreadProcessId(foreground_hwnd, None)

		# Temporarily attach input threads if foreground window belongs to a different thread
		if window_thread_id != 0 and current_thread_id != window_thread_id:
			user32.AttachThreadInput(current_thread_id, window_thread_id, True)
			user32.SetForegroundWindow(hwnd)
			user32.BringWindowToTop(hwnd)
			user32.AttachThreadInput(current_thread_id, window_thread_id, False)
		else:
			user32.SetForegroundWindow(hwnd)
			user32.BringWindowToTop(hwnd)

	return True


