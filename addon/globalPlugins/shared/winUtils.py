class PROCESSENTRY32W(ctypes.Structure):
	_fields_ = [
		('dwSize', wintypes.DWORD),
		('cntUsage', wintypes.DWORD),
		('th32ProcessID', wintypes.DWORD),
		('th32DefaultHeapID', ctypes.c_size_t),
		('th32ModuleID', wintypes.DWORD),
		('cntThreads', wintypes.DWORD),
		('th32ParentProcessID', wintypes.DWORD),
		('pcPriClassBase', wintypes.LONG),
		('dwFlags', wintypes.DWORD),
		('szExeFile', ctypes.c_wchar * 260)
	]

def processExists(exeName: str) -> bool:
	"""
	Checks if a process is currently running on Windows.
	:param exeName: Executable file name (e.g., "notepad.exe")
	:return: True if found, False otherwise (case-insensitive)
	"""
	# Take a snapshot of all running processes
	hSnapshot = ctypes.windll.kernel32.CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0)
	if hSnapshot == INVALID_HANDLE_VALUE:
		return False

	try:
		pe32 = PROCESSENTRY32W()
		pe32.dwSize = ctypes.sizeof(PROCESSENTRY32W)

		# Retrieve information about the first process
		if not ctypes.windll.kernel32.Process32FirstW(hSnapshot, ctypes.byref(pe32)):
			return False

		target_name = exeName.lower()

		# Iterate through the process list
		while True:
			if pe32.szExeFile.lower() == target_name:
				return True
			if not ctypes.windll.kernel32.Process32NextW(hSnapshot, ctypes.byref(pe32)):
				break

		return False
	finally:
		# Always close the handle to prevent memory leaks
		ctypes.windll.kernel32.CloseHandle(hSnapshot)
