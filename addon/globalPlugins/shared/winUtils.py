	"""Search and return the handle (hwnd) of the main window

	whose title contains winTitle. Returns None if not found.
	"""
	found_hwnd = None

	# Define callback prototype for EnumWindows
	WNDENUMPROC = ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)

	def enum_windows_callback(hwnd, lparam):
		nonlocal found_hwnd

		# 1. The window must be visible
		if not user32.IsWindowVisible(hwnd):
			return True

		# 2. Retrieve window title length
		length = user32.GetWindowTextLengthW(hwnd)
		if length == 0:
			return True

		# 3. Retrieve window title
		buffer = ctypes.create_unicode_buffer(length + 1)
		user32.GetWindowTextW(hwnd, buffer, length + 1)
		title = buffer.value

		# 4. Check if title matches
		if winTitle.lower() in title.lower():
			# 5. Ensure it is a top-level window (no owner)
			owner = user32.GetWindow(hwnd, GW_OWNER)

			# 6. Retrieve extended styles
			ex_style = user32.GetWindowLongW(hwnd, GWL_EXSTYLE)
			is_app_window = (ex_style & WS_EX_APPWINDOW) != 0

			# A main window has no owner OR explicitly sets WS_EX_APPWINDOW
			if owner == 0 or is_app_window:
				found_hwnd = hwnd
				return False  # Stop enumeration (window found)

		return True  # Continue enumeration

	# Start window enumeration
	user32.EnumWindows(WNDENUMPROC(enum_windows_callback), 0)

	return found_hwnd


